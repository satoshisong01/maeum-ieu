/**
 * TTS 합성 전 텍스트 정리 (순수 함수 — DB/서버 의존 없음, 회귀 테스트 노출).
 * 음성으로 읽으면 어색한 기호 제거 + 검진 문항 머리말 자연화.
 */

// 1~10 한국어 순서(native) — "첫/두/세…번째"
const NATIVE_ORD = ["", "첫", "두", "세", "네", "다섯", "여섯", "일곱", "여덟", "아홉", "열"];

/**
 * "1/10." 같은 검진 문항 머리말이 TTS에서 "십분의 일"(분수)로 낭독되는 문제 →
 * "첫 번째 문제."로 자연화. **낭독 전용** — 화면 표시 텍스트(${no}/${total})는 그대로 둔다.
 * 머리말 시그니처("N/M." + 공백/끝)만 매칭해 일반 분수("하루 2/3 정도")는 건드리지 않음.
 */
function speakItemHeader(s: string): string {
  return s.replace(/(\d{1,2})\s*\/\s*\d{1,2}\s*\.(\s|$)/g, (_m, n, tail) => {
    const i = parseInt(n, 10);
    const ord = NATIVE_ORD[i] ?? `${i}`;
    return `${ord} 번째 문제.${tail}`;
  });
}

/**
 * 예: "~"(물결표 계열)가 "물결표"로 낭독되는 문제. 공백으로 치환해 낭독 방지 +
 *     "1~2" 같은 숫자 범위가 "12"로 병합되는 것 방지. 별표(마크다운 잔여)도 정리.
 *     "N/M." 검진 머리말 → "N번째 문제." 자연화(2026-06-15 사용자 피드백).
 */
export function sanitizeForTts(s: string): string {
  return speakItemHeader(s)
    .replace(/[~～〜〰]/g, " ") // ~ ～ 〜 〰 → 공백
    .replace(/\*+/g, " ")      // 마크다운 별표 잔여 → 공백("별표" 낭독 방지)
    .replace(/\s{2,}/g, " ")
    .trim();
}
