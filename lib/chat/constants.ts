/** SYSTEM_PROMPT_BASE + COGNITIVE_SCREENING_PROTOCOL에 companion 정보를 치환해 반환 */
export function renderSystemPrompt(params: { companionName?: string; companionRelation?: string }): {
  systemPromptBase: string;
  cognitiveProtocol: string;
} {
  const name = (params.companionName || COMPANION_DEFAULTS.name).trim() || COMPANION_DEFAULTS.name;
  const relation = (params.companionRelation || COMPANION_DEFAULTS.relation).trim() || COMPANION_DEFAULTS.relation;
  const replace = (text: string) =>
    text.replace(/\{COMPANION_NAME\}/g, name).replace(/\{COMPANION_RELATION\}/g, relation);
  return {
    systemPromptBase: replace(SYSTEM_PROMPT_BASE),
    cognitiveProtocol: replace(COGNITIVE_SCREENING_PROTOCOL),
  };
}
