/**
 * 음성 세션 종료 의도 감지 — "그만/조용히 해" 등으로 대화를 멈추려는 발화 판별.
 *
 * 설계 원칙(v3, 2026-07-09 — 3일간 regex가 매일 뒤집힌 끝에 확정):
 * - 오탐(서사·인용을 종료로 오인)의 해악 > 미탐. 대화가 소리 없이 끊기면 어르신은 원인을 모르고,
 *   사별 서사("먼저 가셨어") 직후 침묵은 정서적으로 최악 + 선별 데이터도 끊김.
 *   미탐은 단독 "그만/고만"(BARE)이 항상 동작하므로 복구 수단이 있음.
 * - 부분매칭(CORE) 전면 폐지: "쉴게요 그러더라", "끝내자고 했지", "안녕히 계세요 하고 나왔지" 같은
 *   인용·전달화법은 표현 "뒤에 말이 이어지는" 것이 공통 구조 → 모든 패턴을 발화-끝 앵커로 통일.
 * - 3인칭 사별("먼저 가셨어/가버렸지")은 화자 작별로 불가능한 활용(셨/버)을 lookahead로 배제.
 * - "잘 있어"는 안부 서사("우리 딸 잘 있어요")와 충돌 → 작별 문맥(간다/갈게 동반, 발화 시작, 명령형 -라)만.
 * - 사투리: 고만(=그만), 인제(=이제) 병행.
 * - lookbehind 금지(구형 iOS Safari 파싱 크래시 — 클라이언트 번들). lookahead는 전 브라우저 OK.
 * - 변경은 __tests__/session-end.test.ts 매트릭스를 깨지 않는 "케이스 추가" 방식으로만.
 *
 * 알려진 미탐(의도된 트레이드오프 — 단독 "그만"으로 복구 가능): "그만해 좀"(후행 부사),
 * "불 꺼줘"(기기 명령과 모호), 종결어미 없는 사투리 변형 일부.
 */

const TAIL_END = "[\\s.!?~…]*$"; // 발화 끝(트리밍 후) — STT가 붙이는 문장부호·공백 허용

/** 발화 전체가 종료 그 자체 — "그만", "인제 고만요" */
export const SESSION_END_BARE = new RegExp("^\\s*([이인]제\\s*)?[그고]만(요|이요|입니다)?" + TAIL_END);

/** 발화 끝 앵커 — 종료 의도 표현이 발화를 "끝맺을" 때만 인정 */
export const SESSION_END_TAIL = new RegExp(
  "(" +
    [
      // 그만/고만 + 종료 활용 (피우려고/울었으면 등 서술 연결은 어간 불일치로 자연 배제)
      "([이인]제\\s*)?[그고]만\\s*(해요?|해라|해\\s*줘요?|하자(\\s*이제)?|합시다|할래요?|할게요?|하고\\s*싶[어네다요]{0,3}|하겠[어요습니다]{0,4}|둘래요?|두자|얘기하자|얘기해요?|잘래요?|잘게요?|자야겠[다어]요?|가볼게요?|갈게요?|가야겠[다어]요?|쉬고\\s*싶[어네다요]{0,3}|쉴래요?|됐어요?|됐다|이야)",
      "[이인]제\\s*[그고]만", // "오늘은 이제 그만"
      "(대화|얘기|이야기)\\s*[그고]만",
      "마무리\\s*(하자|할게요?|합시다|하겠[어요습니다]{0,4})",
      "쉬자|쉴게요?|쉴래요?", // "쉬자마자~"는 후행 글자로 앵커 불일치
      "([이인]제\\s*)자야겠[다어]요?",
      "[이인]제\\s*끝(이야|이에요|입니다)?|끝내자", // "이제 끝났어"(서술)는 '났'이 끼어 배제
      "안녕히\\s*계[가-힣]{0,3}",
      "이만\\s*(갈게요?|가볼게요?|들어가[가-힣]{0,3}|끊[가-힣]{0,2}|마무리[가-힣]{0,3})",
      "대화\\s*종료",
      "조용히\\s*해요?|조용히\\s*해\\s*줘요?|조용해|입\\s*다물[어라]{0,2}",
      // 화자 자신의 작별만 — 가(?![셨버])로 3인칭 사별("먼저 가셨어/가버렸지") 배제, 갔(과거)은 음절 불일치로 자연 배제
      "(^|[나저]\\s)먼저\\s*(가(?![셨버])[가-힣]{0,3}|갈[가-힣]{0,3})",
      // 작별 문맥의 "잘 있어" — 안부 서사("우리 딸 잘 있어요")는 불인정
      "(간다|갈게|갈래)[\\s,]*잘\\s*있어[라요]?|^잘\\s*있어[라요]?|잘\\s*있어라",
      "여기까지", // "오늘은 여기까지" — "여기까지 왔어"류는 후행 글자로 배제
    ].join("|") +
  ")" + TAIL_END,
);

/** 발화가 음성 세션 종료 의도인지 판별 (트리밍 포함) */
export function isSessionEndUtterance(text: string): boolean {
  if (!text) return false;
  const t = text.trim();
  return SESSION_END_TAIL.test(t) || SESSION_END_BARE.test(t);
}
