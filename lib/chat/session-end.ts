/**
 * 음성 세션 종료 의도 감지 — "그만/조용히 해" 등으로 대화를 멈추려는 발화 판별.
 *
 * 3일간(2026-07-07~09) regex가 매일 뒤집힌 끝에 모듈로 추출 + __tests__/session-end.test.ts에
 * 매트릭스 고정. 설계 원칙:
 * - 오탐(서사·인용을 종료로 오인)의 해악 > 미탐: 대화가 소리 없이 끊기면 어르신은 원인을 모르고,
 *   특히 사별 서사("영감이 먼저 가셨어") 직후 침묵은 정서적으로 최악 + 선별 데이터도 끊김.
 *   미탐은 단독 "그만"(BARE)이 항상 동작하므로 복구 수단이 있음.
 * - 서사에 잘 섞이는 표현(그만하자/할래·마무리·먼저 가·이제 그만)은 "발화 끝"에서만 인정(TAIL).
 * - 사별 표현("~가 먼저 가셨어")과 작별("나 먼저 가볼게")은 주어로 구분: 먼저-가는 화자 자신(나/저)
 *   또는 발화 시작일 때만 종료로 인정.
 * - "잘 있어"는 조사(은/는/이/가/도) 뒤면 안부 서사("딸은 잘 있어요")이므로 제외(lookbehind).
 * - "끝내자"는 "끝내자마자"(직후 서술) 제외.
 */

/** 발화 전체가 종료 그 자체 — "그만", "이제 그만요" */
export const SESSION_END_BARE = /^\s*(이제\s*)?그만(요|이요|입니다)?[\s.!?~…]*$/;

/** 부분매칭 허용 — 서사·인용에 거의 안 섞이는 고정밀 문구만 */
export const SESSION_END_CORE =
  /(조용히\s*해|조용해|입\s*다물|이제 됐|이제 충분|이제 끝|끝내자(?!마자)|안녕히\s*계|이만 갈|이만 들어가|이만\s*끊|대화\s*종료|쉴게|(?<![은는이가도]\s?)잘\s*있어)/;

/** 발화 끝 앵커 — 종료 의도의 활용형들. 문장 중간(전달화법·서사)이면 미매칭 */
export const SESSION_END_TAIL = new RegExp(
  "(" +
    [
      "이제\\s*그만", // "오늘은 이제 그만"
      "(이제\\s*)?그만\\s*(해요?|해라|하자(\\s*이제)?|합시다|할래요?|할게요?|하고\\s*싶[어네다요]{0,3}|하겠[어요습니다]{0,4}|둘래요?|두자|잘래요?|잘게요?|자야겠[다어]요?|가볼게요?|갈게요?|가야겠[다어]요?)",
      "(대화|얘기|이야기)\\s*그만",
      "마무리\\s*(하자|할게요?|합시다|하겠[어요습니다]{0,4})",
      "쉬자",
      "(^|[나저]\\s)먼저\\s*[가갈][가-힣]{0,3}", // 화자 자신의 작별만("먼저 가볼게/갈게요") — "영감이 먼저 가셨어"(사별)는 주어가 달라 제외
    ].join("|") +
  ")[\\s.!?~…]*$",
);

/** 발화가 음성 세션 종료 의도인지 판별 (트리밍 포함) */
export function isSessionEndUtterance(text: string): boolean {
  if (!text) return false;
  const t = text.trim();
  return SESSION_END_CORE.test(t) || SESSION_END_TAIL.test(t) || SESSION_END_BARE.test(t);
}
